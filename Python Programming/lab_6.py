    "Name: Rohan Kumar, Roll: 23045, Course: CSE, Email: rohan.kumar123@bpmce.ac.in",
    "Name: Anjali Singh, Roll: 23102, Course: ECE, Email: anjali.singh@bpmce.ac.in",
